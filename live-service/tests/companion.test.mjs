import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {api} from '../cloudflare/worker.mjs';
test('D1 companion ownership, retry identity stability and rename persistence',async()=>{
 const db=new DatabaseSync(':memory:');
 for(const file of ['0001_accounts.sql','0002_miro.sql','0005_qb_accounts.sql','0006_calibration_examples.sql'])db.exec(readFileSync(new URL('../cloudflare/migrations/'+file,import.meta.url),'utf8'));
 const env={PRIVY_APP_ID:'test',PRIVY_APP_SECRET:'test',DB:{prepare(sql){return {bind(...params){return {first:async()=>db.prepare(sql).get(...params)||null,run:async()=>({meta:db.prepare(sql).run(...params)}),all:async()=>({results:db.prepare(sql).all(...params)})}}}}}};
 const identityFactory=()=>async token=>({subject:token,email:token+'@example.com',wallets:[]});
 const req=async(user,path,method='GET',body)=>{const r=await api(new Request('https://test'+path,{method,headers:{Authorization:'Bearer '+user,'content-type':'application/json'},body:body?JSON.stringify(body):undefined}),env,new URL('https://test'+path).pathname,identityFactory);return {status:r.status,body:await r.json()}};
 assert.equal((await req('alice','/api/companion','PUT',{name:'Miro'})).status,409);
 await req('alice','/api/me','PUT',{username:'Alice'});await req('bob','/api/me','PUT',{username:'Bob'});
 const a=await req('alice','/api/companion','PUT',{name:'小米'});assert.equal(a.status,200);
 const again=await req('alice','/api/companion','PUT',{name:'小米'});assert.equal(again.body.companion.ai_id,a.body.companion.ai_id);
 assert.equal((await req('alice','/api/companion','PUT',{name:'Wrong Twin',twinId:'miro_wrong'})).status,409);
 assert.equal((await req('alice','/api/companion','PUT',{name:'星星',twinId:a.body.companion.ai_id})).status,200);
 assert.equal((await req('alice','/api/companion')).body.companion.name,'星星');
 assert.equal((await req('bob','/api/companion')).body.companion,null);
 const endpoint='/api/companion/calibration-examples';
 const sample={twinId:a.body.companion.ai_id,id:'d3e5a26b-1860-4d3a-aa6e-1bcf47c624fb',scenario:'Price rises',twinAction:'Wait',ownerAction:'Buy',reason:'Liquidity recovered'};
 const list=endpoint+'?twinId='+sample.twinId;
 assert.equal((await req('alice',endpoint,'POST',sample)).status,400);
 assert.equal((await req('bob',endpoint,'POST',{...sample,consent:'personal-training-v1'})).status,409);
 assert.equal((await req('alice',endpoint,'POST',{...sample,consent:'personal-training-v1'})).status,200);
 assert.equal((await req('alice',endpoint,'POST',{...sample,consent:'personal-training-v1'})).status,200);
 assert.equal((await req('alice',list)).body.examples.length,1);
 assert.equal((await req('alice',endpoint,'DELETE',sample)).status,200);
 assert.deepEqual((await req('alice',list)).body.examples,[]);
 assert.equal((await req('alice','/api/companion','PUT',{name:'<script>'})).status,400);
 const first=await req('alice','/api/points');assert.equal(first.status,200);assert.equal(first.body.currency,'LP');assert.equal(first.body.balance_minor,0);assert.deepEqual(first.body.entries,[]);assert.equal(first.body.topupEnabled,false);
 assert.equal((await req('alice','/api/qb')).body.account.account_id,first.body.account.account_id);
 assert.notEqual((await req('bob','/api/qb')).body.account.account_id,first.body.account.account_id);
 assert.equal((await req('alice','/api/qb','POST',{balance:999})).status,404);
 db.close();
});
