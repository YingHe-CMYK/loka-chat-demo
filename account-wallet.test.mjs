import assert from 'node:assert/strict';
import {normalizeEmail,emailError,usernameError} from './account-flow.js';
import {ensureWallet,transact} from './wallet-demo.js';
import {routeJudgment,traceFor,permissionFor} from './decision-contract.js';
assert.equal(normalizeEmail(' Alex@Example.COM '),'alex@example.com');
for(const x of ['','a@','a b@example.com'])assert.ok(emailError(x));
assert.equal(emailError('alex@example.com'),'');
for(const x of ['a','<script>','x'.repeat(25)])assert.ok(usernameError(x));
assert.equal(usernameError('Alex_研究员'),'');
const s=ensureWallet({profile:{name:'Alex'}}),id=s.wallet.id;ensureWallet(s);assert.equal(s.wallet.id,id);
assert.throws(()=>transact(s.wallet,{kind:'transfer',amount:-1}));assert.throws(()=>transact(s.wallet,{kind:'transfer',amount:101}));
assert.equal(transact(s.wallet,{kind:'approval',amount:5}).balance,100);
assert.equal(transact(s.wallet,{kind:'transfer',amount:5}).balance,95);
assert.equal(routeJudgment({confidence:.99,worth:.9,cold_start:true}).route,'hold_for_letter');
assert.equal(routeJudgment({confidence:.99,worth:.9,permission:'deny'}).route,'blocked');
assert.equal(routeJudgment({confidence:.72,worth:.85}).route,'question');
assert.equal(routeJudgment({confidence:.94,worth:.85,locale:'zh'}).route,'question');
assert.equal(routeJudgment({confidence:.99,worth:.85}).route,'assertion');
assert.equal(traceFor({correctionText:'My note',evidence:[]}).correction_weight,10);
assert.equal(traceFor({}).settled,false);
assert.equal(permissionFor('transfer',{actionPolicy:'block'}),'deny');
console.log('PASS account validation, wallet amounts, judgment thresholds and permission checks');
